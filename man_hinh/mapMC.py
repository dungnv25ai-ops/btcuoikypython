                                    
def _build(m_str, R, C):
    m = [[' ' for _ in range(C)] for _ in range(R)]
    for r, row_str in enumerate(m_str):
        for c, char in enumerate(row_str):
            if r < R and c < C:
                m[r][c] = char
    return [''.join(row) for row in m]

